"""Bake a pinned OCIO display/view transform; runtime never requires Python or OCIO."""
import hashlib
import json
from pathlib import Path
import numpy as np
import PyOpenColorIO as ocio

CONFIG = "cg-config-v4.0.0_aces-v2.0_ocio-v2.5"
SIZE = 129
ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / "src/platform/windows/directx11/color"


def transform(processor, values):
    """Evaluate the official CPU transform on contiguous scene-linear Rec.709 RGB."""
    result = np.array(values, dtype=np.float32, copy=True, order="C")
    processor.applyRGB(result)
    return result


def interpolate(lut, samples):
    """Model D3D trilinear sampling including the exact logarithmic input shaper."""
    position = np.clip(np.log2(1 + samples * 64) / 16, 0, 1) * (SIZE - 1)
    lower = np.minimum(position.astype(int), SIZE - 2)
    fraction = position - lower
    result = np.zeros_like(samples)
    for z in range(2):
        for y in range(2):
            for x in range(2):
                weight = (fraction[:, 0] if x else 1 - fraction[:, 0])
                weight = weight * (fraction[:, 1] if y else 1 - fraction[:, 1])
                weight = weight * (fraction[:, 2] if z else 1 - fraction[:, 2])
                result += lut[lower[:, 2] + z, lower[:, 1] + y, lower[:, 0] + x, :3] * weight[:, None]
    return result


def main():
    """Generate immutable RGBA16F texels and independently sampled reference fixtures."""
    if ocio.__version__ != "2.5.0":
        raise RuntimeError("Regeneration requires OpenColorIO 2.5.0")
    config = ocio.Config.CreateFromBuiltinConfig(CONFIG)
    processor = config.getProcessor(ocio.DisplayViewTransform(
        src="Linear Rec.709 (sRGB)", display="sRGB - Display",
        view="ACES 2.0 - SDR 100 nits (Rec.709)")).getDefaultCPUProcessor()
    axis = (np.exp2(np.linspace(0, 16, SIZE)) - 1) / 64
    blue, green, red = np.meshgrid(axis, axis, axis, indexing="ij")
    rgb = transform(processor, np.stack([red, green, blue], axis=-1).reshape(-1, 3))
    rgba = np.ones((len(rgb), 4), dtype="<f2")
    rgba[:, :3] = rgb
    lut = rgba.reshape(SIZE, SIZE, SIZE, 4).astype(np.float32)
    random = np.random.default_rng(42)
    samples = np.exp2(random.uniform(-14, 9, (50000, 3))).astype(np.float32)
    neutrals = np.repeat(np.geomspace(1e-7, axis[-1], 1000)[:, None], 3, axis=1)
    anchors = np.array([[0, 0, 0], [.01, .01, .01], [.18, .18, .18], [1, 1, 1], [6, 3, 1.5]])
    samples = np.concatenate([samples, neutrals, anchors]).astype(np.float32)
    reference = transform(processor, samples)
    errors = np.abs(interpolate(lut, samples) - reference)
    metrics = {"maximum": float(errors.max()), "p99": float(np.quantile(errors, .99)),
               "rms": float(np.sqrt(np.mean(errors ** 2)))}
    if metrics["maximum"] > .025 or metrics["p99"] > .001 or metrics["rms"] > .00035:
        raise RuntimeError(f"LUT accuracy budget exceeded: {metrics}")
    DEST.mkdir(parents=True, exist_ok=True)
    payload = rgba.tobytes()
    (DEST / "aces_2_sdr_rgba16f.bin").write_bytes(payload)
    metadata = {"ocio": ocio.__version__, "config": CONFIG, "input": "Linear Rec.709 (sRGB)",
                "display": "sRGB - Display", "view": "ACES 2.0 - SDR 100 nits (Rec.709)",
                "edge": SIZE, "format": "RGBA16F little-endian, red fastest", "range": [0, float(axis[-1])],
                "shaper": "log2(1 + max(linearRGB, 0) * 64) / 16", "sha256": hashlib.sha256(payload).hexdigest(),
                "validation_samples": len(samples), "encoded_sRGB_error": metrics}
    (DEST / "aces_2_sdr.json").write_text(json.dumps(metadata, indent=2) + "\n")
    indices = list(range(len(samples)-5, len(samples))) + list(range(24))
    indices.append(int(np.argmax(errors.max(axis=1))))
    lines = ["// Generated by tools/color/generate_aces_sdr.py; do not edit.", "#pragma once",
             "/// Official OCIO input RGB followed by encoded sRGB output; includes the worst sampled interpolation case.",
             "inline constexpr float AcesSdrReference[][6] = {"]
    for index in indices:
        values = np.concatenate([samples[index], reference[index]])
        lines.append("    {" + ",".join(f"{float(v):.9e}f" for v in values) + "},")
    lines.append("};")
    (ROOT / "tests/aces_sdr_reference.hpp").write_text("\n".join(lines) + "\n")
    print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
